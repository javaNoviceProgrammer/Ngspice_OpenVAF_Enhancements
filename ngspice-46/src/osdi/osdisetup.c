/* ====================================================================== *
 *          `.option osdimc` -- automatic Monte-Carlo (statmc)            *
 * ====================================================================== *
 *
 * A Verilog-A parameter declared with `(* std=<sigma> *)` (absolute), or
 * `(* std_rel=<fraction> *)` (relative to the nominal), optionally with
 * `(* dist="gauss"|"uniform" *)`, carries its own statistics: the compiler
 * exports them through the OSDI_STAT_PARAM_INFOS side-table and, with
 * `.option osdimc` (alias `automc`) set, every run-class command draws a
 * fresh value nominal+delta for each such parameter -- through the ordinary
 * parameter setter, so the netlist is never re-expanded and no `reset` is
 * involved. The usual `.control` Monte-Carlo loop simply drops its manual
 * `alter ... gauss()` lines.
 *
 * SEMANTICS, deliberately simple and documented:
 *   - The FIRST run after sourcing is the NOMINAL baseline (trial 1, no
 *     draws): a parameter the deck never set has its nominal resolved by the
 *     model's own setup, so nominals are only knowable after one setup pass.
 *     Draws begin with the second run.
 *   - A MODEL parameter is drawn once per model card per trial -- every
 *     instance sharing the card moves in lockstep (process variation). An
 *     INSTANCE parameter (`(* type="instance" *)`) is drawn independently
 *     per instance (mismatch). The split reuses the existing
 *     model/instance-parameter machinery; nothing new is invented.
 *   - Draws are PURE functions of (mcseed, trial, owner name, param id) --
 *     the same (seed, salt) philosophy as the compiler's $random contract:
 *     `.option mcseed=42` reproduces a whole sequence, and trial N is
 *     re-runnable in isolation. No hidden RNG state advances.
 *   - `alter` of a statistical parameter updates its NOMINAL (the hook in
 *     OSDIparam/OSDImParam below), so later draws recenter on the altered
 *     value; draws are always nominal+delta, never cumulative.
 *   - Turning the option off restores every drawn parameter to its nominal
 *     on the next run.
 *   - A draw that violates the parameter's Verilog-A range is NOT filtered
 *     here (the descriptor does not export ranges): it fails that run with
 *     the device's own located range error, exactly as the same `alter`
 *     would. Size sigmas accordingly.
 */

typedef struct OsdiMcNominal {
  const void *owner; /* model-data or instance-data pointer */
  uint32_t id;
  double nominal;
  bool pinned;       /* E-535 fix (hunt bug 14): a machine write owns the
                        value; the draw applier must leave it alone until the
                        writing command's bracket ends */
} OsdiMcNominal;

static OsdiMcNominal *osdimc_tbl;
static int osdimc_tbl_len;
static int osdimc_tbl_cap;
static CKTcircuit *osdimc_ckt;      /* table belongs to this circuit */
static unsigned long osdimc_trial;  /* 1 = nominal baseline, 2+ = drawn */
static unsigned long osdimc_current_trial(void) { return osdimc_trial; }
static bool osdimc_active;          /* drawn values are currently applied */

/* bug-hunt F5: which trial a setup failure was last reported for */
static unsigned long osdimc_failed_trial_reported;

/* Enhancement-535 (hunt N1/N7/N8): the loop commands and the trial counter.
 *
 * `if_run` advances the trial for every run-class command, which was right
 * for a lone `op` and wrong at both ends of the loop-command spectrum: a
 * per-point `sweep` redrew the sample at EVERY point (a swept curve was N
 * different samples stitched together, and `optimize` fit a stochastic
 * objective -- measured 2.4% silent bias on a closed-form target), while
 * `montecarlo` -- the one command that WANTS a fresh draw per sample -- got
 * none, because its per-sample internal reset zeroed the counter and every
 * sample became the nominal baseline (its own no-variance NOTE fired).
 *
 * Three small levers repair the policy:
 *   - HOLD (OSDImcHoldTrial): a deterministic loop command (sweep's
 *     per-point path, optimize, wcd, loadpull) brackets its inner analyses;
 *     the whole loop consumes exactly ONE trial -- the first held run
 *     advances, every later one RE-APPLIES the same trial's draws (they are
 *     pure functions of (mcseed, trial, owner name, id), so they survive
 *     even an internal re-source that handed the devices their nominals
 *     back). This matches the handed-dc sweep, which is one run.
 *   - PRESERVE (OSDImcPreserveTrial): an INTERNAL reset -- the machinery
 *     montecarlo/highsigma/wcd use to redraw netlist `.param` randoms, and
 *     sweep uses for a `.param` knob -- keeps the trial sequence running,
 *     where a USER reset still restarts it at the baseline. The stale
 *     owner-pointer table is dropped either way and recaptured at setup.
 *   - SCALE (OSDImcSigmaScale): `highsigma -scale` could inflate only the
 *     netlist sigmas it owns; attribute-declared (* std *) sigmas were
 *     un-inflatable, so rare-failure analysis over osdimc variability had
 *     no instrument. The factor multiplies every drawn sigma (gaussian and
 *     uniform half-width alike) while it is set. */
/* E-536 fix (hunt bug 16): the hold is a DEPTH, not a flag. A loop command
 * nested as another's -analysis (an `optimize` whose objective is a swept
 * curve) used to release the OUTER command's bracket when the inner one
 * finished -- measured: one fresh Monte-Carlo trial PER optimizer evaluation,
 * the exact stochastic-objective bias the hold exists to eliminate. Only the
 * outermost edges reset held_advanced and the pins; the whole nest is ONE
 * sample. Callers keep their own held flag so an error path that never took
 * the bracket (a parse failure, the sweep->dc handover) cannot pop someone
 * else's. */
static int osdimc_hold_depth;     /* >0: loop command(s) holding one sample */
static bool osdimc_held_advanced; /* that hold has taken its one trial */
static bool osdimc_keep_trial;    /* the NEXT circuit change is internal */
static bool osdimc_internal_change; /* E-536 fix (hunt bug 12): CircuitChanged
                                       consumed a keep -- bless the next
                                       ckt-pointer change at OSDImcNewRun */
static double osdimc_scale = 1.0; /* sigma inflation, 1.0 = off */
/* E-537 (hunt P): the loop commands' own `-seed`, mixed into the draw key.
 * osdimc keys on `.option mcseed`, so `montecarlo -seed 1` and `-seed 999`
 * produced BYTE-IDENTICAL samples -- and varying the seed is precisely how one
 * checks a Monte-Carlo estimate is stable, so every "independent" replication
 * returned the same points and looked perfectly reproducible when nothing had
 * been re-sampled. Applied only when the user actually passed -seed, so a deck
 * that never mentions it keeps the draws it has today. */
static uint32_t osdimc_seed_extra;

void OSDImcSeedOffset(unsigned s) { osdimc_seed_extra = (uint32_t) s; }

/* ===================== E-538: scoped sigma inflation =====================
 *
 * `highsigma -scale` inflates EVERY gauss statistical parameter in the
 * circuit, and the importance weight is a PRODUCT over all of them. Its
 * variance therefore grows exponentially with their number, so on any deck
 * with per-instance mismatch the estimator collapses: E-537 measured a true
 * P(fail) of 0.297 reported as 2.5e-11 once twenty bystander devices -- ones
 * the metric cannot even depend on -- joined the product, and added an
 * effective-sample-size guard that says the answer is unusable.
 *
 * Saying "unusable" is only half an answer. The reason those dimensions are
 * in the product at all is that nothing could name a subset, so this is the
 * other half: `-inflate <spec>` restricts inflation (and therefore the
 * weight) to the parameters the failure actually depends on, which is what
 * makes the run low-dimensional enough to estimate.
 *
 * A spec is either a bare parameter name -- `vth0`, meaning that parameter
 * wherever it occurs -- or the project's ordinary accessor spelling
 * `@owner[param]`, with `*` allowed as the owner. Matching is
 * case-insensitive, as everywhere else in the name surface.
 *
 * With no specs the behaviour is exactly what it was: everything inflates. */
typedef struct {
  char *owner; /* model-card or instance name, or "*" */
  char *param;
} OsdiMcScope;

static OsdiMcScope *osdimc_scope;
static int osdimc_scope_len, osdimc_scope_cap;
static int osdimc_scope_hits; /* how many draws the specs actually matched */

void OSDImcScaleScopeClear(void) {
  int i;
  for (i = 0; i < osdimc_scope_len; i++) {
    tfree(osdimc_scope[i].owner);
    tfree(osdimc_scope[i].param);
  }
  osdimc_scope_len = 0;
  osdimc_scope_hits = 0;
}

int OSDImcScaleScopeHits(void) { return osdimc_scope_hits; }

/* Parse one spec. Returns false (and says nothing) on a shape this does not
 * recognise; the caller reports, since it knows the command name. */
bool OSDImcScaleScopeAdd(const char *spec) {
  const char *owner = "*", *param = NULL;
  char buf[256], *lb, *rb;

  if (!spec || !*spec)
    return false;
  if (*spec == '@') {
    if (strlen(spec) >= sizeof buf)
      return false;
    strcpy(buf, spec + 1);
    lb = strchr(buf, '[');
    rb = strrchr(buf, ']');
    if (!lb || !rb || rb <= lb + 1 || lb == buf)
      return false;
    *lb = '\0';
    *rb = '\0';
    owner = buf;
    param = lb + 1;
  } else {
    if (strchr(spec, '[') || strchr(spec, ']'))
      return false;
    param = spec;
  }
  if (!*param)
    return false;

  if (osdimc_scope_len == osdimc_scope_cap) {
    osdimc_scope_cap = osdimc_scope_cap ? 2 * osdimc_scope_cap : 8;
    osdimc_scope = TREALLOC(OsdiMcScope, osdimc_scope, osdimc_scope_cap);
  }
  osdimc_scope[osdimc_scope_len].owner = copy(owner);
  osdimc_scope[osdimc_scope_len].param = copy(param);
  osdimc_scope_len++;
  return true;
}

/* The inflation factor for ONE parameter: the command's lambda when it is in
 * scope, 1.0 (no inflation, and hence weight 1) when it is not. */
static double osdimc_scale_for(const char *owner, const char *param) {
  int i;
  if (osdimc_scale == 1.0 || osdimc_scope_len == 0)
    return osdimc_scale;        /* unscoped: everything, exactly as before */
  if (!param)
    return 1.0;
  for (i = 0; i < osdimc_scope_len; i++) {
    if (!cieq(osdimc_scope[i].param, (char *) param))
      continue;
    if (osdimc_scope[i].owner[0] == '*' && osdimc_scope[i].owner[1] == '\0')
      return osdimc_scale;
    if (owner && cieq(osdimc_scope[i].owner, (char *) owner))
      return osdimc_scale;
  }
  return 1.0;
}

/* E-537 (hunt O): is `.option osdimc` drawing for this circuit? The frontend
 * asks so it can say that a stratified-sampling request does not reach these
 * draws. Defined here beside the option test it wraps. */
bool OSDImcActive(void) { return osdimc_enabled(); }

/* E-537 (hunt J): step past the nominal baseline so a sampling command's N
 * samples are N DRAWS. osdimc's contract makes the first run after sourcing
 * the nominal baseline, and `montecarlo N` consumed it as sample 1 -- so on a
 * freshly sourced deck (the normal way to run it) N-1 samples were random and
 * one was deterministic, while the banner said "N random samples". The yield
 * and its Wilson interval treated that fixed point as a draw, and the effective
 * count depended on how many run-class commands happened earlier in the
 * session. Idempotent: a sequence already past the baseline is untouched. */
void OSDImcSkipBaseline(void) {
  if (osdimc_enabled() && osdimc_trial < 1)
    osdimc_trial = 1;
}

/* E-535 fix (hunt bug 1): the current trial's draws are NOT in parameter
 * storage yet -- the table was empty when OSDImcNewRun ran, because an
 * internal re-source preceded this run. OSDIsetup consumes this: it applies
 * the draws right after its own setup loops have resolved the nominals, and
 * BEFORE OSDItemp evaluates the init-resident code. Recomputed by every
 * OSDImcNewRun, so it cannot go stale across runs; within one run a repeated
 * OSDIsetup (the E-471 rebuild path) just re-applies bit-identical values. */
static bool osdimc_apply_pending;
static bool osdimc_apply_is_pending(void) { return osdimc_apply_pending; }

static void osdimc_clear_pins(void);

void OSDImcHoldTrial(bool on) {
  if (on) {
    if (osdimc_hold_depth++ == 0) {
      osdimc_held_advanced = false;
      /* E-535 fix (hunt bug 14): pins never cross the OUTERMOST bracket edge
       * -- a value pinned by one sweep's restore must not freeze the next
       * command's draws. Inner edges leave both alone: the nest shares one
       * sample and one pin set. */
      osdimc_clear_pins();
    }
  } else if (osdimc_hold_depth > 0 && --osdimc_hold_depth == 0) {
    osdimc_held_advanced = false;
    osdimc_clear_pins();
  }
}

void OSDImcPreserveTrial(void) { osdimc_keep_trial = true; }

void OSDImcSigmaScale(double s) { osdimc_scale = (s > 0.0) ? s : 1.0; }

/* E-536 fix (hunt bugs 5/6): a keyboard interrupt longjmps from anywhere in a
 * loop command straight to the prompt, skipping every bracket clear -- the
 * hold froze all later runs on one sample, a leaked highsigma inflation
 * silently scaled every later draw, and a dangling preserve carried an
 * interrupted run's trial sequence through a USER re-source (observed
 * continuing at trial 91828). Called from ft_sigintr_cleanup(): once control
 * is back at the prompt, no loop command is legitimately in progress. */
void OSDImcInterruptReset(void) {
  osdimc_hold_depth = 0;
  osdimc_held_advanced = false;
  osdimc_keep_trial = false;
  osdimc_internal_change = false;
  osdimc_scale = 1.0;
  osdimc_seed_extra = 0;          /* E-537 (hunt P) */
  osdimc_clear_pins();
}

/* E-536 fix (hunt bug 8, the -center half): `optimize -center` evaluates a
 * YIELD objective -- an inner Monte-Carlo per candidate. Each candidate must
 * see the SAME set of osdimc trials, or the objective is stochastic across
 * candidates; rewinding to a checkpoint taken before the search replays the
 * identical trial window (draws are pure functions of the counter), so the
 * yield estimate includes osdimc variation AND is deterministic. Rewind only
 * ever moves the counter backwards. */
unsigned long OSDImcTrialCheckpoint(void) { return osdimc_trial; }

void OSDImcTrialRewind(unsigned long t) {
  if (osdimc_trial > t)
    osdimc_trial = t;
}

/* bug-hunt F2: a (re-)sourced or `reset` deck reallocates the model/instance
 * data blocks, so every stored owner pointer is stale. The circuit loader
 * calls this (inp_dodeck, fresh and reuse paths alike); the ckt-pointer check
 * in OSDImcNewRun stays as a second line of defense. */
void OSDImcCircuitChanged(void) {
  osdimc_tbl_len = 0;
  osdimc_active = false;
  osdimc_failed_trial_reported = 0;
  /* E-536 fix (hunt bug 12): the preserve flag is consumed HERE, at the
   * circuit change it was set for, so it can never dangle into a later USER
   * reset (the sweep's reset-path restore is the last reset of its run, with
   * no run after it to consume the flag -- a user's next `reset` then
   * wrongly continued the sequence). What survives to OSDImcNewRun is the
   * blessing for the pointer change this reload causes; a USER change both
   * restarts the sequence and revokes any blessing. */
  if (osdimc_keep_trial) {          /* Enhancement-535: internal resets keep */
    osdimc_keep_trial = false;      /* the sample sequence running          */
    osdimc_internal_change = true;
  } else {
    osdimc_trial = 0;
    osdimc_internal_change = false;
  }
}

static bool osdimc_armed_now(void) {
  return osdimc_trial > 0 && osdimc_enabled();
}

static void osdimc_report_setup_failure(void) {
  if (osdimc_failed_trial_reported == osdimc_trial)
    return;
  osdimc_failed_trial_reported = osdimc_trial;
  fprintf(stderr,
          "osdimc: trial %lu FAILED during setup; result vectors from the "
          "previous successful run remain current.\n",
          osdimc_trial);
}

static OsdiMcNominal *osdimc_find(const void *owner, uint32_t id) {
  for (int i = 0; i < osdimc_tbl_len; i++) {
    if (osdimc_tbl[i].owner == owner && osdimc_tbl[i].id == id) {
      return &osdimc_tbl[i];
    }
  }
  return NULL;
}

static void osdimc_insert(const void *owner, uint32_t id, double nominal) {
  if (osdimc_tbl_len == osdimc_tbl_cap) {
    osdimc_tbl_cap = osdimc_tbl_cap ? 2 * osdimc_tbl_cap : 16;
    osdimc_tbl = TREALLOC(OsdiMcNominal, osdimc_tbl, osdimc_tbl_cap);
  }
  osdimc_tbl[osdimc_tbl_len++] =
      (OsdiMcNominal){.owner = owner, .id = id, .nominal = nominal};
}

static void osdimc_clear_pins(void) {
  for (int i = 0; i < osdimc_tbl_len; i++)
    osdimc_tbl[i].pinned = false;
}

/* E-535 fix (hunt bug 14): OSDIparam/OSDImParam report every successful
 * parameter write here. Machine routes -- a `sweep` point push, a `.dc` level
 * write, a `sens` perturbation, an optimizer candidate -- deliberately do NOT
 * recenter the nominal (bug-hunt F1), but they must WIN over the trial's
 * draw: re-applying nominal+delta over the pushed value flattened
 * `sweep @n1[dr]` to one point repeated N times. The write pins the entry;
 * the draw applier skips pinned entries; pins clear at every loop-command
 * bracket edge (OSDImcHoldTrial) and at every un-held OSDImcNewRun (a fresh
 * standalone trial redraws everything -- which keeps `alter` recentering
 * observable on the very next run, exactly as check 19 pins). Writes made
 * before the first capture find no entry and pin nothing, so deck parsing
 * and re-sourcing stay untouched. */
void OSDImcNoteParamWrite(const void *owner, uint32_t id) {
  OsdiMcNominal *e = osdimc_find(owner, id);
  if (e)
    e->pinned = true;
}

static bool osdimc_enabled(void) {
  return cp_getvar("osdimc", CP_BOOL, NULL, 0) ||
         cp_getvar("automc", CP_BOOL, NULL, 0);
}

/* splitmix64: the draw is a pure hash of its inputs, no stored RNG state */
static uint64_t osdimc_mix(uint64_t z) {
  z += 0x9e3779b97f4a7c15ull;
  z = (z ^ (z >> 30)) * 0xbf58476d1ce4e5b9ull;
  z = (z ^ (z >> 27)) * 0x94d049bb133111ebull;
  return z ^ (z >> 31);
}

static uint64_t osdimc_hash_str(const char *s) {
  uint64_t h = 0xcbf29ce484222325ull; /* FNV-1a */
  for (; s && *s; s++) {
    h = (h ^ (uint64_t)(unsigned char)*s) * 0x100000001b3ull;
  }
  return h;
}

/* E-537 (hunt P): the per-trial base key, shared by the draw applier and the
 * importance-weight walker so the two can never disagree about which value was
 * drawn. */
static uint64_t osdimc_kbase(int seed) {
  uint64_t k = osdimc_mix(((uint64_t)(uint32_t)seed << 32) ^ 0x6f7364696d63ull);
  if (osdimc_seed_extra)
    k = osdimc_mix(k ^ ((uint64_t)osdimc_seed_extra << 1));
  return osdimc_mix(k ^ osdimc_trial);
}

/* uniform in (0,1), both ends excluded (log() below needs nonzero) */
static double osdimc_u01(uint64_t h) {
  return ((double)(h >> 11) + 0.5) * (1.0 / 9007199254740992.0);
}

/* the standard-normal deviate of a gauss draw -- shared by the draw itself
 * and the importance-weight walker (E-536 fix, hunt bug 7), so the two can
 * never disagree about which value was drawn */
static double osdimc_n01(uint64_t key) {
  double u1 = osdimc_u01(osdimc_mix(key ^ 1));
  double u2 = osdimc_u01(osdimc_mix(key ^ 2));
  return sqrt(-2.0 * log(u1)) * cos(2.0 * M_PI * u2);
}

static double osdimc_delta(uint64_t key, uint32_t dist, double std,
                           double nominal, double scale) {
  double sigma = (dist & OSDI_DIST_REL) ? std * fabs(nominal) : std;
  if (dist & OSDI_DIST_UNIFORM) {
    /* E-536 fix (hunt bug 7): SCALE does NOT inflate uniforms, matching the
     * netlist SSS policy exactly ("uniform .params are bounded, so SSS does
     * not inflate them -- they carry weight 1", randnumb.c). An inflated
     * uniform can land where the TRUE density is zero, which no finite
     * importance weight represents. std is the HALF-WIDTH. */
    double u1 = osdimc_u01(osdimc_mix(key ^ 1));
    return sigma * (2.0 * u1 - 1.0);
  }
  /* Enhancement-535: highsigma inflation (gauss only); E-538: `scale` is
   * this parameter's own factor, 1.0 when `-inflate` left it out of scope. */
  return sigma * scale * osdimc_n01(key);
}

/* Capture the nominal of every statistical parameter that does not have one
 * yet, reading the CURRENT resolved value. Called at the end of OSDItemp --
 * after setup_model/setup_instance have filled in the defaults of parameters
 * the deck never set (Enhancement-476 recorded that defaults are applied
 * during setup) -- and only inserting MISSING entries, so the drawn values a
 * later trial has already written are never mistaken for nominals. */
static void osdimc_capture(const OsdiRegistryEntry *entry, GENmodel *inModel) {
  const OsdiDescriptor *descr = entry->descriptor;
  const OsdiStatParamInfo *infos = entry->stat_param_infos;

  if (entry->num_stat_params == 0 || !infos || !osdimc_enabled()) {
    return;
  }

  for (GENmodel *gen_model = inModel; gen_model;
       gen_model = gen_model->GENnextModel) {
    void *model = osdi_model_data(gen_model);
    for (uint32_t s = 0; s < entry->num_stat_params; s++) {
      uint32_t id = infos[s].param_id;
      if (id >= descr->num_instance_params) { /* model parameter */
        if (!osdimc_find(model, id)) {
          double val;
          void *src = descr->access(NULL, model, id, ACCESS_FLAG_READ);
          if (src) {
            memcpy(&val, src, sizeof(double));
            osdimc_insert(model, id, val);
          }
        }
      } else { /* instance parameter */
        for (GENinstance *gen_inst = gen_model->GENinstances; gen_inst;
             gen_inst = gen_inst->GENnextInstance) {
          void *inst = osdi_instance_data((OsdiRegistryEntry *)entry, gen_inst);
          if (!osdimc_find(inst, id)) {
            double val;
            void *src = descr->access(inst, model, id,
                                      ACCESS_FLAG_READ | ACCESS_FLAG_INSTANCE);
            if (src) {
              memcpy(&val, src, sizeof(double));
              osdimc_insert(inst, id, val);
            }
          }
        }
      }
    }
  }
}

/* Called by OSDItemp once its model/instance loops are done (success or not:
 * a failed card's params simply stay uncaptured and undrawn). */
void osdimc_capture_chain(const OsdiRegistryEntry *entry, GENmodel *inModel) {
  osdimc_capture(entry, inModel);
}

/* bug-hunt F1: a USER wrote a scalar real parameter (`alter`/`altermod`,
 * wildcards included -- frontend/spiceif.c's doset_user is the only caller):
 * if it is a statistical one with a captured nominal, the write IS the new
 * nominal, so the distribution recenters. Machine writes (.dc parameter
 * sweeps, the `sweep` command's per-point and restore writes, sensitivity
 * perturbations) go through OSDIparam/OSDImParam directly and deliberately
 * do NOT recenter -- keying on the setter turned a sweep's save/restore into
 * a permanent nominal shift. */
/* E-537 (hunt G): a command that writes through the USER channel but is really
 * a MACHINE writer brackets its writes with this, so the recentering below is
 * skipped. `aging` computes a dose from a stress simulation and applies it with
 * `alter @dev[agepar] = <dose>` -- the user route -- which permanently moved the
 * statistical nominal of an aging parameter declared with (* std *). Because the
 * dose is computed from a DRAWN sample, that wrote the draw's randomness into
 * the nominal and made it random-walk across repeated aging runs (measured
 * 0 -> 0.495253 -> 0.49919 -> 0.499013, non-monotonic). E-531 settled the rule
 * this restores: only writes the USER typed recenter. */
static bool osdimc_machine_write;


void OSDImcMachineWrite(bool on) { osdimc_machine_write = on; }

void OSDImcNoteUserWrite(int typecode, GENinstance *dev, GENmodel *mdl,
                         int param_id, double value) {
  const void *owner;
  OsdiMcNominal *e;

  if (osdimc_machine_write)                /* E-537 (hunt G) */
    return;
  if (!osdi_devtype_is_osdi(typecode) || param_id < 0)
    return;
  if (dev) {
    OsdiRegistryEntry *entry = osdi_reg_entry_inst(dev);
    const OsdiDescriptor *descr = entry->descriptor;
    if ((uint32_t)param_id >= descr->num_instance_params)
      return;
    owner = osdi_instance_data(entry, dev);
  } else if (mdl) {
    OsdiRegistryEntry *entry = osdi_reg_entry_model(mdl);
    const OsdiDescriptor *descr = entry->descriptor;
    if ((uint32_t)param_id < descr->num_instance_params ||
        (uint32_t)param_id >= descr->num_params)
      return;
    owner = osdi_model_data(mdl);
  } else {
    return;
  }
  e = osdimc_find(owner, (uint32_t)param_id);
  if (e) {
    e->nominal = value;
  }
}

/* Write value into one statistical parameter through the descriptor's
 * ordinary setter (the exact channel OSDIparam/OSDImParam use). */
/* bug-hunt F13: a huge sigma can overflow Box-Muller to +-inf; a non-finite
 * value must never reach parameter storage (a declared range catches it only
 * when one exists -- an unbounded parameter would be poisoned silently). */
static bool osdimc_draw_ok(const OsdiDescriptor *descr, uint32_t id,
                           double value) {
  if (isfinite(value))
    return true;
  fprintf(stderr,
          "osdimc: trial %lu: draw for parameter '%s' is not finite "
          "(sigma too large?); the parameter is left at its nominal.\n",
          osdimc_trial, descr->param_opvar[id].name[0]);
  return false;
}

static void osdimc_write(const OsdiDescriptor *descr, void *inst, void *model,
                         uint32_t id, double value) {
  void *dst;
  if (id < descr->num_instance_params) {
    dst = descr->access(inst, NULL, id, ACCESS_FLAG_SET | ACCESS_FLAG_INSTANCE);
  } else {
    dst = descr->access(NULL, model, id, ACCESS_FLAG_SET);
  }
  if (dst) {
    memcpy(dst, &value, sizeof(double));
  }
}

/* The per-run entry point: called by if_run for every run-class command
 * (`run`, `tran`, `op`, ... -- everything but `resume`). */
void OSDImcNewRun(CKTcircuit *ckt) {
  int seed = 1;
  bool verbose;

  if (!ckt) {
    return;
  }

  /* a different (re-sourced) circuit invalidates every stored nominal.
   * E-536 fix (hunt bug 12): what is consumed here is the BLESSING
   * OSDImcCircuitChanged left for the pointer change an internal reset
   * caused (the preserve flag itself is consumed at the circuit change, so
   * it cannot dangle into a later USER reset). A preserve that never saw its
   * circuit change -- the reset was interrupted mid-reload -- is swept up
   * here too, as the old code did. */
  {
    bool keep = osdimc_internal_change || osdimc_keep_trial;
    osdimc_internal_change = false;
    osdimc_keep_trial = false;
    if (ckt != osdimc_ckt) {
      osdimc_ckt = ckt;
      osdimc_tbl_len = 0;
      osdimc_active = false;
      if (!keep)
        osdimc_trial = 0;
    }
  }

  if (!osdimc_enabled()) {
    /* option switched off: put every drawn parameter back to its nominal */
    if (osdimc_active) {
      for (int type = 0; type < DEVmaxnum; type++) {
        if (!ckt->CKThead[type] || !osdi_devtype_is_osdi(type)) {
          continue;
        }
        OsdiRegistryEntry *entry = osdi_reg_entry_model(ckt->CKThead[type]);
        const OsdiDescriptor *descr = entry->descriptor;
        const OsdiStatParamInfo *infos = entry->stat_param_infos;
        if (entry->num_stat_params == 0 || !infos) {
          continue;
        }
        for (GENmodel *gen_model = ckt->CKThead[type]; gen_model;
             gen_model = gen_model->GENnextModel) {
          void *model = osdi_model_data(gen_model);
          for (uint32_t s = 0; s < entry->num_stat_params; s++) {
            uint32_t id = infos[s].param_id;
            if (id >= descr->num_instance_params) {
              OsdiMcNominal *e = osdimc_find(model, id);
              if (e) {
                osdimc_write(descr, NULL, model, id, e->nominal);
              }
            } else {
              for (GENinstance *gen_inst = gen_model->GENinstances; gen_inst;
                   gen_inst = gen_inst->GENnextInstance) {
                void *inst = osdi_instance_data(entry, gen_inst);
                OsdiMcNominal *e = osdimc_find(inst, id);
                if (e) {
                  osdimc_write(descr, inst, model, id, e->nominal);
                }
              }
            }
          }
        }
      }
      osdimc_active = false;
    }
    osdimc_trial = 0;
    osdimc_apply_pending = false;
    return;
  }

  /* E-535 fix (hunt bug 14): outside a hold every run is a fresh trial that
   * redraws everything, so no pin survives into it; under a hold the loop
   * command's machine writes keep owning their values until the bracket ends
   * (OSDImcHoldTrial clears at the outermost edges). */
  if (osdimc_hold_depth == 0)
    osdimc_clear_pins();

  /* Enhancement-535: under a loop command's hold the whole loop is ONE
   * sample -- take a single trial on the first held run, and afterwards
   * RE-APPLY that same trial (an internal re-source may have put nominals
   * back; the draws re-derive bit-identically from (seed, trial, owner,
   * id)). The baseline trial has nothing to re-apply. */
  if (osdimc_hold_depth > 0) {
    if (!osdimc_held_advanced) {
      osdimc_held_advanced = true;
      osdimc_trial++;
    } else if (osdimc_trial <= 1) {
      osdimc_apply_pending = false;
      return;
    }
  } else {
    osdimc_trial++;
  }
  if (!cp_getvar("mcseed", CP_NUM, &seed, 0)) {
    seed = 1;
  }
  verbose = cp_getvar("osdimc_verbose", CP_BOOL, NULL, 0);

  /* E-535 fix (hunt bug 15): the baseline NEVER draws -- explicitly, not by
   * the accident of an empty table. An optimize/-center flow or an
   * `unset osdimc`/`set osdimc` toggle can reach trial 1 with a POPULATED
   * table, and the apply loop then drew on the run every contract calls the
   * nominal baseline. */
  if (osdimc_trial < 2) {
    osdimc_apply_pending = false;
    return;
  }

  /* E-535 fix (hunt bug 1): an internal re-source dropped the table, so the
   * nominals (deck defaults included) are resolvable only after one setup
   * pass -- the draws cannot land here. Flag them pending; OSDIsetup captures
   * and applies them before OSDItemp evaluates the init-resident code. */
  if (osdimc_tbl_len == 0) {
    osdimc_apply_pending = true;
    return;
  }
  osdimc_apply_pending = false;

  for (int type = 0; type < DEVmaxnum; type++) {
    if (!ckt->CKThead[type] || !osdi_devtype_is_osdi(type)) {
      continue;
    }
    osdimc_apply_type(ckt, type, seed, verbose);
  }
}

/* Enhancement-535: apply the CURRENT trial's draws to one device type. Split
 * out of OSDImcNewRun so OSDIsetup can run it for a PENDING trial: OSDImcNewRun
 * fires from if_run BEFORE the analysis sets the circuit up, so on the first
 * run after any (re-)source the nominal table is still empty at draw time and
 * nothing could be written -- exactly wrong for a preserved trial after a loop
 * command's INTERNAL reset (montecarlo redrew its .params, dropped the table,
 * and every sample then computed the nominal). OSDIsetup applies the pending
 * draws right after its setup loops resolve the nominals -- and before
 * OSDItemp, so the init-resident code sees them. Draws are pure functions of
 * (mcseed, trial, owner name, id), so a repeated application (the E-471
 * rebuild path runs OSDIsetup twice) is bit-identical. */
static void osdimc_apply_type(CKTcircuit *ckt, int type, int seed,
                              bool verbose) {
  {
    OsdiRegistryEntry *entry = osdi_reg_entry_model(ckt->CKThead[type]);
    const OsdiDescriptor *descr = entry->descriptor;
    const OsdiStatParamInfo *infos = entry->stat_param_infos;
    if (entry->num_stat_params == 0 || !infos) {
      return;
    }

    uint64_t kbase = osdimc_kbase(seed);   /* E-537 (hunt P) */

    for (GENmodel *gen_model = ckt->CKThead[type]; gen_model;
         gen_model = gen_model->GENnextModel) {
      void *model = osdi_model_data(gen_model);
      uint64_t kmodel =
          osdimc_mix(kbase ^ osdimc_hash_str((char *)gen_model->GENmodName));

      for (uint32_t s = 0; s < entry->num_stat_params; s++) {
        uint32_t id = infos[s].param_id;

        if (id >= descr->num_instance_params) { /* process: per model card */
          OsdiMcNominal *e = osdimc_find(model, id);
          if (!e || e->pinned) {
            continue; /* no nominal (a failed card stays undrawn), or a
                         machine write owns the value (hunt bug 14) */
          }
          /* E-538: this parameter's own inflation (1.0 when out of scope) */
          double sc = osdimc_scale_for((char *)gen_model->GENmodName,
                                       descr->param_opvar[id].name[0]);
          if (sc != 1.0)
            osdimc_scope_hits++;
          double val = e->nominal + osdimc_delta(osdimc_mix(kmodel ^ id),
                                                 infos[s].dist, infos[s].std,
                                                 e->nominal, sc);
          if (!osdimc_draw_ok(descr, id, val))
            val = e->nominal;
          osdimc_write(descr, NULL, model, id, val);
          osdimc_active = true;
          if (verbose) {
            printf("osdimc: trial %lu: %s:%s = %g (nominal %g)\n",
                   osdimc_trial, (char *)gen_model->GENmodName,
                   descr->param_opvar[id].name[0], val, e->nominal);
          }
        } else { /* mismatch: per instance */
          for (GENinstance *gen_inst = gen_model->GENinstances; gen_inst;
               gen_inst = gen_inst->GENnextInstance) {
            void *inst = osdi_instance_data(entry, gen_inst);
            OsdiMcNominal *e = osdimc_find(inst, id);
            if (!e || e->pinned) {
              continue;
            }
            uint64_t kinst =
                osdimc_mix(kbase ^ osdimc_hash_str((char *)gen_inst->GENname));
            double sc = osdimc_scale_for((char *)gen_inst->GENname,
                                         descr->param_opvar[id].name[0]);
            if (sc != 1.0)
              osdimc_scope_hits++;
            double val = e->nominal + osdimc_delta(osdimc_mix(kinst ^ id),
                                                   infos[s].dist, infos[s].std,
                                                   e->nominal, sc);
            if (!osdimc_draw_ok(descr, id, val))
              val = e->nominal;
            osdimc_write(descr, inst, model, id, val);
            osdimc_active = true;
            if (verbose) {
              printf("osdimc: trial %lu: %s:%s = %g (nominal %g)\n",
                     osdimc_trial, (char *)gen_inst->GENname,
                     descr->param_opvar[id].name[0], val, e->nominal);
            }
          }
        }
      }
    }
  }
}

/* E-536 fix (hunt bug 7): the log importance weight of the CURRENT trial's
 * osdimc draws under the active sigma inflation.
 *
 * `highsigma -scale` inflates the attribute-declared gauss sigmas (above),
 * but mc_sample_weight() accumulates likelihood ratios only for the netlist
 * `.param` draws -- so with OSDI-only variability every sample carried
 * weight 1 and P(fail) was estimated under the INFLATED density (measured
 * 0.42 reported where the true value is 0.354). This walker recomputes, for
 * every gauss statistical parameter the applier would draw, the same
 * standard-normal deviate n (draws are pure functions of (seed, trial,
 * owner, id)) and sums the per-dimension log ratio
 *
 *     log[ phi(z) / ((1/lambda) phi(z/lambda)) ]  with  z = lambda*n
 *   = log(lambda) - n^2 (lambda^2 - 1) / 2 .
 *
 * Recomputing instead of accumulating during apply makes double application
 * (the E-471 rebuild path re-runs OSDIsetup) harmless by construction.
 * Uniform draws are not inflated (see osdimc_delta) and contribute 0;
 * pinned entries were not drawn and contribute 0. Returns 0 whenever no
 * inflation is active, so callers can apply exp() unconditionally. */
double OSDImcSampleLogLR(CKTcircuit *ckt) {
  double logw = 0.0;
  int seed = 1;

  if (!ckt || osdimc_scale == 1.0 || osdimc_trial < 2 || !osdimc_enabled())
    return 0.0;
  if (!cp_getvar("mcseed", CP_NUM, &seed, 0))
    seed = 1;

  uint64_t kbase = osdimc_kbase(seed);    /* E-537 (hunt P) */

  for (int type = 0; type < DEVmaxnum; type++) {
    if (!ckt->CKThead[type] || !osdi_devtype_is_osdi(type))
      continue;
    OsdiRegistryEntry *entry = osdi_reg_entry_model(ckt->CKThead[type]);
    const OsdiDescriptor *descr = entry->descriptor;
    const OsdiStatParamInfo *infos = entry->stat_param_infos;
    if (entry->num_stat_params == 0 || !infos)
      continue;

    for (GENmodel *gen_model = ckt->CKThead[type]; gen_model;
         gen_model = gen_model->GENnextModel) {
      void *model = osdi_model_data(gen_model);
      uint64_t kmodel =
          osdimc_mix(kbase ^ osdimc_hash_str((char *)gen_model->GENmodName));

      for (uint32_t s = 0; s < entry->num_stat_params; s++) {
        uint32_t id = infos[s].param_id;
        if (infos[s].dist & OSDI_DIST_UNIFORM)
          continue;
        if (id >= descr->num_instance_params) {
          OsdiMcNominal *e = osdimc_find(model, id);
          if (!e || e->pinned)
            continue;
          /* E-538: weight EXACTLY the dimensions that were inflated. A
           * parameter `-inflate` left out of scope was drawn at its true
           * sigma, so it carries no likelihood ratio -- and keeping it out of
           * the product is the whole point: the weight stays low-dimensional
           * and the estimate usable. */
          double sc = osdimc_scale_for((char *)gen_model->GENmodName,
                                       descr->param_opvar[id].name[0]);
          if (sc == 1.0)
            continue;
          double n = osdimc_n01(osdimc_mix(kmodel ^ id));
          logw += log(sc) - 0.5 * n * n * (sc * sc - 1.0);
        } else {
          for (GENinstance *gen_inst = gen_model->GENinstances; gen_inst;
               gen_inst = gen_inst->GENnextInstance) {
            void *inst = osdi_instance_data(entry, gen_inst);
            OsdiMcNominal *e = osdimc_find(inst, id);
            if (!e || e->pinned)
              continue;
            double sc = osdimc_scale_for((char *)gen_inst->GENname,
                                         descr->param_opvar[id].name[0]);
            if (sc == 1.0)
              continue;                      /* E-538: not inflated, weight 1 */
            uint64_t kinst =
                osdimc_mix(kbase ^ osdimc_hash_str((char *)gen_inst->GENname));
            double n = osdimc_n01(osdimc_mix(kinst ^ id));
            logw += log(sc) - 0.5 * n * n * (sc * sc - 1.0);
          }
        }
      }
    }
  }
  return logw;
}
