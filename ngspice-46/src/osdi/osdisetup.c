/*
 * Handles any errors raised by the setup_instance and setup_model functions
 */
/* bug-hunt F5/F6 forward decls (definitions live in the osdimc block below) */
static void osdimc_report_setup_failure(void);
static bool osdimc_armed_now(void);
static bool osdimc_enabled(void);

static int handle_init_info(OsdiInitInfo info, const OsdiDescriptor *descr,
                            const OsdiNgspiceHandle *handle, void *inst,
                            void *model) {
  if (info.flags & (EVAL_RET_FLAG_FATAL | EVAL_RET_FLAG_FINISH)) {
    /* Enhancement-56: a Verilog-A $fatal/$finish during setup is the model
     * rejecting its parameters/configuration (the model's own message was
     * already printed via the log callback). Say so instead of surfacing
     * E_PANIC's baffling "impossible error - can't occur". */
    errMsg = tprintf("a Verilog-A device rejected its configuration during "
                     "setup (%s raised)",
                     (info.flags & EVAL_RET_FLAG_FATAL) ? "$fatal" : "$finish");
    return (E_PRIVATE);
  }

  if (info.num_errors == 0) {
    return (OK);
  }

  for (uint32_t i = 0; i < info.num_errors; i++) {
    OsdiInitError *err = &info.errors[i];
    switch (err->code) {
    case INIT_ERR_OUT_OF_BOUNDS: {
      /* bug-hunt F6: name the owner and the offending value, not just the
       * parameter -- in a Monte-Carlo loop over many devices a bare
       * "Parameter rd is out of bounds!" is unattributable. */
      uint32_t id = err->payload.parameter_id;
      char *param = descr->param_opvar[id].name[0];
      bool scalar_real =
          (descr->param_opvar[id].flags & PARA_TY_MASK) == PARA_TY_REAL &&
          descr->param_opvar[id].len == 0;
      void *src = NULL;
      if (id < descr->num_instance_params) {
        if (inst)
          src = descr->access(inst, model, id,
                              ACCESS_FLAG_READ | ACCESS_FLAG_INSTANCE);
      } else if (model) {
        src = descr->access(NULL, model, id, ACCESS_FLAG_READ);
      }
      if (scalar_real && src) {
        double v;
        memcpy(&v, src, sizeof(double));
        printf("Parameter %s of '%s' is out of bounds (value %g)!\n", param,
               handle && handle->name ? (char *)handle->name : descr->name, v);
      } else {
        printf("Parameter %s of '%s' is out of bounds!\n", param,
               handle && handle->name ? (char *)handle->name : descr->name);
      }
      /* bug-hunt F5: in an osdimc loop a failed trial leaves the PREVIOUS
       * run's plot current -- say so in-band, once per trial. */
      if (osdimc_armed_now())
        osdimc_report_setup_failure();
      break;
    }
    default:
      printf("Unknown OSDO init error code %d!\n", err->code);
    }
  }
  errMsg = tprintf("%i errors occurred during initialization", info.num_errors);
  return (E_PRIVATE);
}

/*
 * The OSDI instance data contains the `node_mapping` array.
 * Here an index is stored for each node. This function initializes this array
 * with its indicies {0, 1, 2, 3, .., n}.
 * The node collapsing information generated by setup_instance is used to
 * replace these initial indicies with those that a node is collapsed into.
 * For example collapsing nodes i and j sets node_mapping[i] = j.
 *
 * Terminals can never be collapsed in ngspice because they are allocated by
 * ngspice instead of OSDI. Therefore any node collapsing that involves nodes
 * `i < connected_terminals` is ignored.
 *
 * @param const OsdiDescriptor *descr The OSDI descriptor
 * @param void *inst The instance data connected_terminals
 * @param uint32_t connected_terminals The number of terminals that are not
 * internal nodes.
 *
 * @returns The number of nodes required after collapsing.
 * */
/* Enhancement-401: is this terminal short redundant?
 *
 * The compiler emits a real 0 V source for `V(a,b) <+ 0` between two TERMINALS,
 * because collapse_nodes below cannot honour a collapse hint there. That equation
 * is exactly right when a and b are two DISTINCT connected circuit nodes, and
 * redundant otherwise -- and a redundant 0 V source is a singular row (its current
 * appears nowhere else). "Otherwise" is: the two terminals are the same circuit
 * node, the short is to ground and the terminal IS ground, or an endpoint is not a
 * connected terminal at all (in which case the ordinary collapse already applies).
 */
static bool term_short_is_redundant(const OsdiTermShortInfo *ts,
                                    const int *terminals,
                                    uint32_t connected_terminals) {
  if (ts->node_1 >= connected_terminals) {
    return true;
  }
  int n1 = terminals[ts->node_1];
  if (ts->node_2 == UINT32_MAX) {
    return n1 == 0; /* shorted to ground, and already IS ground */
  }
  if (ts->node_2 >= connected_terminals) {
    return true;
  }
  return n1 == terminals[ts->node_2];
}

/* Remove `node` from the instance's node mapping, exactly as collapse_nodes does
 * for a pair collapsed to ground. Returns the new node count. */
static uint32_t drop_node(const OsdiDescriptor *descr, uint32_t *node_mapping,
                          uint32_t num_nodes, uint32_t node) {
  uint32_t from = node_mapping[node];
  if (from == UINT32_MAX) {
    return num_nodes; /* already gone */
  }
  for (uint32_t j = 0; j < descr->num_nodes; j++) {
    if (node_mapping[j] == from) {
      node_mapping[j] = UINT32_MAX;
    } else if (node_mapping[j] > from && node_mapping[j] != UINT32_MAX) {
      node_mapping[j] -= 1;
    }
  }
  return num_nodes - 1;
}

/* Enhancement-532: rank of a group representative for the collapse-merge
 * decision. Ground can absorb anything, a connected terminal can absorb
 * internals but never another terminal (ngspice allocates terminal nodes,
 * OSDI cannot merge them), internals merge freely. */
#define OSDI_GRP_GROUND 0
#define OSDI_GRP_TERMINAL 1
#define OSDI_GRP_INTERNAL 2
static int osdi_group_rank(uint32_t rep, uint32_t connected_terminals) {
  if (rep == UINT32_MAX)
    return OSDI_GRP_GROUND;
  return rep < connected_terminals ? OSDI_GRP_TERMINAL : OSDI_GRP_INTERNAL;
}

static uint32_t collapse_nodes(const OsdiDescriptor *descr, void *inst,
                               uint32_t connected_terminals,
                               const OsdiTermShortInfo *term_shorts,
                               uint32_t num_term_shorts,
                               const int *terminals,
                               uint32_t *syn_pairs, uint32_t *num_syn) {
  /* access data inside instance */
  uint32_t *node_mapping =
      (uint32_t *)(((char *)inst) + descr->node_mapping_offset);
  bool *collapsed = (bool *)(((char *)inst) + descr->collapsed_offset);

  /* without collapsing just return the total number of nodes */
  uint32_t num_nodes = descr->num_nodes;

  /*  populate nodes with themselves*/
  for (uint32_t i = 0; i < descr->num_nodes; i++) {
    node_mapping[i] = i;
  }

  /* Enhancement-401: drop the branch current of any terminal short the netlist
   * has already made, before the ordinary collapses renumber anything. */
  for (uint32_t i = 0; i < num_term_shorts; i++) {
    if (term_short_is_redundant(&term_shorts[i], terminals, connected_terminals)) {
      num_nodes =
          drop_node(descr, node_mapping, num_nodes, term_shorts[i].flow_node);
    }
  }

  /* Enhancement-532: the executed hints are processed as group merges over
   * the CURRENT mapping. The old loop had three holes, all reachable through
   * chains of hints: a merge whose endpoints both already mapped to
   * connected terminals was silently DROPPED (the V(x,y)=0 equation simply
   * vanished and the device fell open -- physically identical netlists gave
   * opposite answers depending on whether the short was spelled directly or
   * through an internal node); a group already collapsed to ground being
   * merged again re-mapped its UINT32_MAX members onto the other group,
   * quietly UN-grounding them; and a hint between two nodes already in the
   * same group renumbered everything above the representative and
   * decremented num_nodes although no row disappeared. Terminal-terminal
   * (and terminal-ground) merges are now recorded in `syn_pairs` -- local
   * indices, UINT32_MAX for ground -- and OSDIsetup stamps a synthetic
   * ideal 0 V source for each, which is exactly the equation the hint
   * expressed and exactly what the compiler itself emits for the direct
   * spelling (Enhancement-401). */
  for (uint32_t i = 0; i < descr->num_collapsible; i++) {
    /* check if the collapse hint (V(x,y) <+ 0) was executed */
    if (!collapsed[i]) {
      continue;
    }

    uint32_t n1 = descr->collapsible[i].node_1;
    uint32_t n2 = descr->collapsible[i].node_2;
    uint32_t r1 = node_mapping[n1];
    uint32_t r2 = (n2 == UINT32_MAX) ? UINT32_MAX : node_mapping[n2];

    if (r1 == r2) {
      continue; /* already in the same group (or both ground): redundant */
    }

    /* order so that r2 is the group that survives: ground beats terminal
     * beats internal; among internals the smaller index survives (the old
     * "to is always the smaller node" invariant, which the renumbering
     * below relies on) */
    int k1 = osdi_group_rank(r1, connected_terminals);
    int k2 = osdi_group_rank(r2, connected_terminals);
    if (k1 < k2 || (k1 == k2 && r1 < r2)) {
      uint32_t tr = r1;
      r1 = r2;
      r2 = tr;
      int tk = k1;
      k1 = k2;
      k2 = tk;
    }

    if (k1 == OSDI_GRP_TERMINAL) {
      /* terminal-terminal or terminal-ground: ngspice owns these nodes and
       * they cannot be merged -- record the pair for a synthetic 0 V source */
      syn_pairs[2 * *num_syn] = r1;
      syn_pairs[2 * *num_syn + 1] = r2;
      *num_syn += 1;
      continue;
    }

    /* r1 is an internal group: dissolve it into r2 (ground, a terminal, or a
     * lower-numbered internal -- all numerically smaller than r1, so the
     * compaction below cannot disturb r2) */
    for (uint32_t j = 0; j < descr->num_nodes; j++) {
      if (node_mapping[j] == r1) {
        node_mapping[j] = r2;
      } else if (node_mapping[j] > r1 && node_mapping[j] != UINT32_MAX) {
        node_mapping[j] -= 1;
      }
    }
    num_nodes -= 1;
  }
  return num_nodes;
}

/* replace node mapping local to the current instance (created by
 * collapse_nodes) with global node indicies allocated with CKTmkVolt */
static void write_node_mapping(const OsdiDescriptor *descr, void *inst,
                               uint32_t *nodes) {
  uint32_t *node_mapping =
      (uint32_t *)(((char *)inst) + descr->node_mapping_offset);
  for (uint32_t i = 0; i < descr->num_nodes; i++) {
    if (node_mapping[i] == UINT32_MAX) {
      /* gnd node */
      node_mapping[i] = 0;
    } else {
      node_mapping[i] = nodes[node_mapping[i]];
    }
  }
}

/* LRM 3.6.1: stamp each of this instance's nodes with the abstol its nature
 * declares, so the convergence test judges it by the tolerance the model asked
 * for rather than the circuit-wide default. Nodes shared with other devices
 * keep the TIGHTEST claim; a model that declares nothing leaves the node at 0
 * and the global tolerance continues to apply. */
static void apply_node_abstol(CKTcircuit *ckt, const OsdiRegistryEntry *entry,
                              const OsdiDescriptor *descr, void *inst) {
  uint32_t *node_mapping;
  uint32_t i;

  if (!ckt || !entry || !entry->natures) {
    return;
  }
  node_mapping = (uint32_t *)(((char *)inst) + descr->node_mapping_offset);
  for (i = 0; i < descr->num_nodes; i++) {
    double tol = osdi_node_abstol(entry, i);
    uint32_t gnode = node_mapping[i];
    CKTnode *n;
    if (tol <= 0.0 || gnode == 0) {
      continue; /* nothing declared, or ground */
    }
    for (n = ckt->CKTnodes; n; n = n->next) {
      if ((uint32_t)n->number == gnode) {
        if (n->natabstol <= 0.0 || tol < n->natabstol) {
          if (ft_ngdebug) {
            fprintf(stderr, "OSDI: node %u convergence abstol = %g "
                            "(declared by its nature)\n", gnode, tol);
          }
          n->natabstol = tol;
        }
        break;
      }
    }
  }
}

/* NGSPICE state vectors for an instance are always continous so we just write
 * state_start .. state_start + num_state to state_idx */
static void write_state_ids(const OsdiDescriptor *descr, void *inst,
                            uint32_t state_start) {
  uint32_t *state_idx = (uint32_t *)(((char *)inst) + descr->state_idx_off);
  for (uint32_t i = 0; i < descr->num_states; i++) {
    state_idx[i] = state_start + i;
  }
}

static int init_matrix(SMPmatrix *matrix, const OsdiDescriptor *descr,
                       void *inst) {
  uint32_t *node_mapping =
      (uint32_t *)(((char *)inst) + descr->node_mapping_offset);

  double **jacobian_ptr_resist =
      (double **)(((char *)inst) + descr->jacobian_ptr_resist_offset);

  for (uint32_t i = 0; i < descr->num_jacobian_entries; i++) {
    uint32_t equation = descr->jacobian_entries[i].nodes.node_1;
    uint32_t unknown = descr->jacobian_entries[i].nodes.node_2;
    equation = node_mapping[equation];
    unknown = node_mapping[unknown];
    double *ptr = SMPmakeElt(matrix, (int)equation, (int)unknown);

    if (ptr == NULL) {
      return (E_NOMEM);
    }
    jacobian_ptr_resist[i] = ptr;
    uint32_t react_off = descr->jacobian_entries[i].react_ptr_off;
    // complex number for ac analysis
    if (react_off != UINT32_MAX) {

      double **jacobian_ptr_react = (double **)(((char *)inst) + react_off);
      *jacobian_ptr_react = ptr + 1;
    }
  }
  return (OK);
}

